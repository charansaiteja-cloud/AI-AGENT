from __future__ import annotations

import asyncio
import logging
import mimetypes
import shutil
import uuid
from dataclasses import dataclass
from pathlib import Path

from fastapi import UploadFile

from backend.app.config import settings

logger = logging.getLogger(__name__)

_TEXT_EXTENSIONS = {".txt", ".md", ".csv", ".json"}
_IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".gif", ".webp"}
_CHUNK_SIZE = 1024 * 1024


class AttachmentError(Exception):
    def __init__(self, message: str, status_code: int = 400) -> None:
        super().__init__(message)
        self.message = message
        self.status_code = status_code


@dataclass(frozen=True)
class StoredUpload:
    original_filename: str
    stored_filename: str
    content_type: str
    file_size: int
    extension: str


class AttachmentService:
    """Stores uploads safely and turns readable files into prompt context."""

    def __init__(self, upload_dir: Path | None = None) -> None:
        self.upload_dir = upload_dir or settings.upload_dir

    async def save_upload(
        self,
        file: UploadFile,
        conversation_id: int,
    ) -> StoredUpload:
        original_filename = Path(file.filename or "").name
        if not original_filename:
            raise AttachmentError("A filename is required.", status_code=400)

        extension = Path(original_filename).suffix.lower()
        if extension not in settings.allowed_extensions:
            raise AttachmentError(
                "That file type is not supported. Upload an image, PDF, or a text-based file.",
                status_code=415,
            )

        content_type = (
            file.content_type
            or mimetypes.guess_type(original_filename)[0]
            or "application/octet-stream"
        )

        if (
            extension in _IMAGE_EXTENSIONS
            and not content_type.startswith("image/")
            and content_type != "application/octet-stream"
        ):
            raise AttachmentError(
                "The image content type does not match its extension.",
                status_code=415,
            )

        destination_dir = self.upload_dir / str(conversation_id)
        destination_dir.mkdir(parents=True, exist_ok=True)

        stored_filename = f"{uuid.uuid4().hex}{extension}"
        destination = destination_dir / stored_filename
        file_size = 0

        try:
            with destination.open("wb") as handle:
                while True:
                    chunk = await file.read(_CHUNK_SIZE)
                    if not chunk:
                        break
                    file_size += len(chunk)
                    if file_size > settings.max_upload_size:
                        raise AttachmentError(
                            "File is too large. Maximum size is "
                            f"{settings.max_upload_size // (1024 * 1024)} MB.",
                            status_code=413,
                        )
                    handle.write(chunk)
        except AttachmentError:
            destination.unlink(missing_ok=True)
            raise
        except Exception:
            destination.unlink(missing_ok=True)
            logger.exception("Failed to store attachment")
            raise AttachmentError(
                "The attachment could not be stored.",
                status_code=500,
            ) from None
        finally:
            await file.close()

        if file_size == 0:
            destination.unlink(missing_ok=True)
            raise AttachmentError("The uploaded file is empty.", status_code=400)

        return StoredUpload(
            original_filename=original_filename,
            stored_filename=stored_filename,
            content_type=content_type,
            file_size=file_size,
            extension=extension,
        )

    def path_for(self, conversation_id: int, stored_filename: str) -> Path:
        # stored_filename is generated by the server, but take only the final
        # path component defensively in case a row is ever corrupted.
        safe_name = Path(stored_filename).name
        return self.upload_dir / str(conversation_id) / safe_name

    def delete_file(self, conversation_id: int, stored_filename: str) -> None:
        try:
            self.path_for(conversation_id, stored_filename).unlink(missing_ok=True)
        except OSError:
            logger.warning("Could not delete attachment file", exc_info=True)

    def delete_conversation_files(self, conversation_id: int) -> None:
        directory = self.upload_dir / str(conversation_id)
        if directory.exists():
            shutil.rmtree(directory, ignore_errors=True)

    async def extract_text(
        self,
        conversation_id: int,
        original_filename: str,
        stored_filename: str,
    ) -> str:
        extension = Path(original_filename).suffix.lower()
        path = self.path_for(conversation_id, stored_filename)

        if not path.is_file():
            return ""

        if extension in _TEXT_EXTENSIONS:
            return await asyncio.to_thread(self._read_text, path)

        if extension == ".pdf":
            return await asyncio.to_thread(self._read_pdf, path)

        return ""

    async def build_context(
        self,
        attachments: list[tuple[int, str, str, str]],
    ) -> str:
        """Build a bounded prompt block from (conversation, name, stored, type)."""
        blocks: list[str] = []
        remaining = settings.max_attachment_text_chars

        for conversation_id, original, stored, content_type in attachments:
            if remaining <= 0:
                break

            text = await self.extract_text(conversation_id, original, stored)
            if text:
                text = text[:remaining]
                remaining -= len(text)
                blocks.append(f"--- Attached file: {original} ---\n{text}")
            else:
                blocks.append(
                    f"[Attached file: {original} ({content_type}). No text preview is available.]"
                )

        if not blocks:
            return ""

        return "\n\n" + "\n\n".join(blocks)

    @staticmethod
    def _read_text(path: Path) -> str:
        try:
            return path.read_text(encoding="utf-8", errors="replace")[
                : settings.max_attachment_text_chars
            ]
        except OSError:
            return ""

    @staticmethod
    def _read_pdf(path: Path) -> str:
        try:
            from pypdf import PdfReader

            reader = PdfReader(str(path))
            pages: list[str] = []
            for page in reader.pages[:10]:
                pages.append(page.extract_text() or "")
                if sum(len(item) for item in pages) >= (settings.max_attachment_text_chars):
                    break
            return "\n".join(pages)[: settings.max_attachment_text_chars]
        except Exception:
            logger.warning("Could not extract PDF text", exc_info=True)
            return ""
